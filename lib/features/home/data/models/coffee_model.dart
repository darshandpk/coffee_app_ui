class CoffeeModel {
  final int id;
  final String image;
  final String title;
  final String subtitle;
  final double price;
  final String category;
  final double rating;

  CoffeeModel({
    required this.id,
    required this.image,
    required this.title,
    required this.subtitle,
    required this.price,
    required this.category,
    required this.rating,
  });
}